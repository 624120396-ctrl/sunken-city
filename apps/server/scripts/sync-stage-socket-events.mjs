import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';

const sharedPath = resolve(import.meta.dirname, '../../shared/stage/stage-contract.ts');
const outputPath = resolve(import.meta.dirname, '../src/generated/stage-socket-events.ts');
const shared = await readFile(sharedPath, 'utf8');
const match = shared.match(/export const STAGE_SOCKET_EVENTS = (\{[\s\S]*?\}) as const;/);
if (!match) throw new Error('STAGE_SOCKET_EVENTS was not found in the shared contract');
await writeFile(outputPath, `// Generated by scripts/sync-stage-socket-events.mjs from apps/shared/stage/stage-contract.ts. Do not edit.\nexport const STAGE_SOCKET_EVENTS = ${match[1]} as const;\n`);
