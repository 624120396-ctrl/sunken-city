// 解析技能点公式
export function calculateSkillPoints(
  formula: string,
  attrs: { str: number; con: number; siz: number; dex: number; app: number; int: number; pow: number; edu: number }
): number {
  const tokens = formula.split('+');
  let total = 0;
  for (const token of tokens) {
    const t = token.trim();
    if (t.startsWith('max(')) {
      const match = t.match(/max\(([^,]+),([^)]+)\)\*(\d+)/i);
      if (match) {
        const a1 = match[1].trim().toLowerCase();
        const a2 = match[2].trim().toLowerCase();
        const mult = parseInt(match[3] || '1', 10);
        const v1 = attrs[a1 as keyof typeof attrs] || 0;
        const v2 = attrs[a2 as keyof typeof attrs] || 0;
        total += Math.max(v1, v2) * mult;
        continue;
      }
    }
    const [attr, multStr] = t.split('*');
    const multiplier = parseInt(multStr || '1', 10);
    const value = attrs[attr.toLowerCase() as keyof typeof attrs] || 0;
    total += value * multiplier;
  }
  return total;
}

