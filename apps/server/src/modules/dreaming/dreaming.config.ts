export function getRandomText(key: string, position: CardPosition): string {
  const card = DREAM_CARD_DEFINITIONS.find((c) => c.key === key);
  if (!card) return '一片深海般的沉默。';
  const pool = position === 'upright' ? card.uprightPool : card.reversedPool;
  return pool[Math.floor(Math.random() * pool.length)];
}

export function getRandomTentacleBuff(): TentacleBuff {
  return TENTACLE_BUFFS[Math.floor(Math.random() * TENTACLE_BUFFS.length)];
}

export function getCardMeta(key: string): DreamCardDefinition | undefined {
  return DREAM_CARD_DEFINITIONS.find((c) => c.key === key);
}
